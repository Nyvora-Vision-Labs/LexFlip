"""Low-overlap, force-preserving paraphrases of the LEXFLIP sources.

This is the `paraphrase` cell of the specificity control (see specificity.py):
what a real simplifier produces, with surface form moved a long way and legal
force left where it was. A metric that reads overlap will penalise these; one
that reads legal meaning should not.

Generated by Llama-3.3-70B-Instruct (AWQ) served on the cluster (src/cluster/
serve_judge.sh, reached through an SSH tunnel), deterministically (temperature
0), one request per sentence, cached to results/paraphrases.jsonl. Llama is
also one of the two judges, so its scores on this cell are read with that
self-preference in mind; the DeepSeek judge and the untrained metrics are not
exposed to it.

Items are kept only if they are well formed, keep every number of the source,
and overlap the source by at most PARA_MAX_JACCARD of their tokens.
"""
import os, sys, json, re, urllib.request
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import probes as P
from augment import _tok, _wellformed

OUT = os.path.join(P.ROOT, "results", "paraphrases.jsonl")
ENDPOINT = os.environ.get("JUDGE_LOCAL_ENDPOINT", "http://localhost:8010/v1/chat/completions")
MODEL = "meta-llama/Llama-3.3-70B-Instruct"
MAX_J = float(os.environ.get("PARA_MAX_JACCARD", "0.6"))

SYSTEM = ("Vous êtes légiste au Québec. Vous réécrivez des dispositions "
          "législatives en langage clair sans en changer la portée juridique.")
PROMPT = """Réécrivez la disposition suivante en français clair, pour un lecteur non juriste.

Exigences:
- La portée juridique doit rester EXACTEMENT la même: mêmes personnes visées, \
même modalité (obligation, permission, interdiction), mêmes conditions, \
exceptions, délais, montants et renvois.
- N'ajoutez rien et ne retirez rien qui ait un effet juridique.
- Changez la formulation et la structure de la phrase autant que possible: \
évitez de reprendre les mots de l'original quand un équivalent clair existe.
- Une seule phrase ou deux au plus.

DISPOSITION:
{s}

Répondez uniquement par un objet JSON: {{"reformulation": "..."}}"""


def _jacc(a, b):
    A, B = set(_tok(a)), set(_tok(b))
    return len(A & B) / max(1, len(A | B))


def _nums(s):
    return sorted(re.findall(r"\d+(?:[.,]\d+)?", s))


def _one(i, s):
    body = dict(model=MODEL, temperature=0.0, max_tokens=600,
                messages=[{"role": "system", "content": SYSTEM},
                          {"role": "user", "content": PROMPT.format(s=s)}])
    req = urllib.request.Request(ENDPOINT, data=json.dumps(body).encode(),
                                 headers={"Content-Type": "application/json"})
    txt = json.load(urllib.request.urlopen(req, timeout=600))["choices"][0]["message"]["content"]
    try:
        para = json.loads(txt[txt.index("{"):txt.rindex("}") + 1])["reformulation"].strip()
    except (ValueError, KeyError):
        para = ""
    return dict(i=i, source=s, paraphrase=para)


def generate(workers=16):
    from concurrent.futures import ThreadPoolExecutor
    import threading
    done = {}
    if os.path.exists(OUT):
        for line in open(OUT, encoding="utf-8"):
            r = json.loads(line); done[r["i"]] = r
    todo = [(i, s) for i, s in enumerate(P.SOURCES) if i not in done]
    lock = threading.Lock()
    with open(OUT, "a", encoding="utf-8") as f, ThreadPoolExecutor(workers) as ex:
        for r in ex.map(lambda a: _one(*a), todo):
            with lock:
                f.write(json.dumps(r, ensure_ascii=False) + "\n"); f.flush()
                done[r["i"]] = r
                if len(done) % 50 == 0:
                    print("  %d/%d" % (len(done), P.n), flush=True)
    return done


def load(require_filter=True):
    """[(source_index, paraphrase)] that pass the filters, in source order."""
    rows = [json.loads(l) for l in open(OUT, encoding="utf-8")]
    out = []
    for r in sorted(rows, key=lambda r: r["i"]):
        p, s = r["paraphrase"], r["source"]
        ok = (p and _wellformed(p) and _nums(p) == _nums(s) and _jacc(s, p) <= MAX_J)
        if ok or not require_filter:
            out.append((r["i"], p))
    return out


if __name__ == "__main__":
    generate()
    kept = load()
    J = [_jacc(P.SOURCES[i], p) for i, p in kept]
    print("kept %d / %d; mean Jaccard %.3f (max %.3f)"
          % (len(kept), P.n, sum(J) / len(J), max(J)))
